export function suggestNames(prefix: string, existing: string[] = [], limit = 8): string[] {
  const p = prefix.trim().toLowerCase()
  if (!p) return []
  const taken = new Set(existing.map((e) => e.toLowerCase()))
  return NAME_PRESETS.filter((n) => n.toLowerCase().startsWith(p) && !taken.has(n.toLowerCase())).slice(0, limit)
}
