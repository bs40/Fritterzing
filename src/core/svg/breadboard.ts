/**
 * Breadboard view generator.
 *
 * Raster artwork is embedded untouched inside an SVG wrapper (no tracing);
 * SVG artwork is inlined with all ids prefixed. Invisible connector targets
 * (connectorNpin / connectorNterminal) are overlaid at the user's positions.
 */
import type { Part } from '../model'
import { fzConnectorId } from '../model'
import { naturalToMm, outputSizePx, outputTransform, sizeToMm, effectiveCrop } from '../artwork'
import { fmt } from '../units'
import { el } from '../xml'
import { cleanFragment, namespaceDecls, prefixIds, splitSvg, svgRoot } from './common'

export interface BakedRaster {
  /** data URL of the artwork with crop and rotation already applied */
  dataUrl: string
  widthPx: number
  heightPx: number
}

export interface BreadboardOptions {
  bakedRaster?: BakedRaster | null
  /** draw a visible placeholder when there is no artwork */
  placeholder?: boolean
}

export const TERMINAL_MM = 0.2

export function generateBreadboardSvg(part: Part, opts: BreadboardOptions = {}): string {
  const art = part.artwork
  const widthMm = art?.widthMm ?? 20
  const heightMm = art?.heightMm ?? 10
  const parts: string[] = []
  parts.push(`<g id="breadboard">`)

  if (art) {
    parts.push(artworkMarkup(part, opts))
  } else {
    parts.push(
      el('rect', {
        x: 0,
        y: 0,
        width: fmt(widthMm),
        height: fmt(heightMm),
        fill: '#e8e8e8',
        stroke: '#888888',
        'stroke-width': 0.3
      })
    )
  }

  part.connectors.forEach((c, i) => {
    if (!c.breadboard || !art) return
    const id = fzConnectorId(c, i)
    const p = naturalToMm(art, c.breadboard)
    const w = Math.max(0.4, sizeToMm(art, c.breadboard.w))
    const h = Math.max(0.4, sizeToMm(art, c.breadboard.h))
    const visible = c.showInArtwork
    const paint = visible
      ? { fill: '#9d9d9d', 'fill-opacity': 0.8, stroke: '#3a3a3a', 'stroke-width': 0.15 }
      : { fill: '#ffffff', 'fill-opacity': 0.001, stroke: 'none' }
    const useCircle = c.marker === 'circle' || c.marker === 'target' || c.marker === 'crosshair'
    if (useCircle) {
      parts.push(el('circle', { id: `${id}pin`, cx: fmt(p.x), cy: fmt(p.y), r: fmt(Math.min(w, h) / 2), ...paint }))
    } else {
      parts.push(
        el('rect', { id: `${id}pin`, x: fmt(p.x - w / 2), y: fmt(p.y - h / 2), width: fmt(w), height: fmt(h), ...paint })
      )
    }
    parts.push(
      el('rect', {
        id: `${id}terminal`,
        x: fmt(p.x - TERMINAL_MM / 2),
        y: fmt(p.y - TERMINAL_MM / 2),
        width: fmt(TERMINAL_MM),
        height: fmt(TERMINAL_MM),
        fill: 'none',
        stroke: 'none'
      })
    )
  })

  parts.push(`</g>`)
  return svgRoot(widthMm, heightMm, parts.join('\n'), { comment: `Generated by Fritterzing: ${part.metadata.title}` })
}

function artworkMarkup(part: Part, opts: BreadboardOptions): string {
  const art = part.artwork!
  const out = outputSizePx(art)
  const sx = out.w > 0 ? art.widthMm / out.w : 1
  const sy = out.h > 0 ? art.heightMm / out.h : 1

  if (art.kind === 'raster') {
    if (opts.bakedRaster) {
      const b = opts.bakedRaster
      return el('image', {
        x: 0,
        y: 0,
        width: fmt(art.widthMm),
        height: fmt(art.heightMm),
        preserveAspectRatio: 'none',
        'xlink:href': b.dataUrl
      })
    }
    // Un-baked: embed the original pixels and apply crop/rotation with a transform.
    // (Cropping without baking cannot clip, Fritzing's renderer lacks clipPath;
    // the renderer bakes rasters before export so this is only a fallback.)
    const c = effectiveCrop(art)
    const image = el('image', {
      x: 0,
      y: 0,
      width: fmt(art.pixelWidth),
      height: fmt(art.pixelHeight),
      preserveAspectRatio: 'none',
      'xlink:href': art.dataUrl
    })
    const needsTransform = art.rotation !== 0 || c.x !== 0 || c.y !== 0
    const inner = needsTransform ? `<g transform="${outputTransform(art)}">${image}</g>` : image
    return `<g transform="scale(${fmt(sx)} ${fmt(sy)})">${inner}</g>`
  }

  // SVG artwork: inline the original content, ids prefixed, scaled to physical size.
  const info = art.svgText ? splitSvg(art.svgText) : null
  if (!info) return ''
  const vb = info.viewBox ?? { x: 0, y: 0, w: art.pixelWidth, h: art.pixelHeight }
  const inner = prefixIds(cleanFragment(info.inner), 'art-')
  const ns = namespaceDecls(info.attrs)
  const vbScaleX = vb.w > 0 ? art.pixelWidth / vb.w : 1
  const vbScaleY = vb.h > 0 ? art.pixelHeight / vb.h : 1
  // natural px space == viewBox space scaled by vbScale; then crop/rotate; then mm.
  const t = `scale(${fmt(sx)} ${fmt(sy)}) ${outputTransform(art)} scale(${fmt(vbScaleX)} ${fmt(vbScaleY)}) translate(${fmt(-vb.x)} ${fmt(-vb.y)})`
  return `<g id="art-artwork"${ns} transform="${t}">${inner}</g>`
}
